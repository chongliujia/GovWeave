// Optional end-to-end check. Requires Playwright and Chrome; neither is a runtime dependency.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { spawn } = require('node:child_process');
const http = require('node:http');

async function main() {
  const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'govweave-browser-'));
  const port = process.env.GOVWEAVE_TEST_PORT || '18081';
  const origin = `http://127.0.0.1:${port}`;
  const output = path.resolve('dist/browser-smoke');
  await fs.mkdir(output, { recursive: true });
  const env = { ...process.env, GOVWEAVE_LISTEN_ADDR: `127.0.0.1:${port}`, GOVWEAVE_DATA_DIR: dataDir };
  for (const key of ['GOVWEAVE_PUBLIC_URL', 'GOVWEAVE_ORGANIZATION_NAME', 'GOVWEAVE_ADMIN_TOKEN_FILE']) delete env[key];
  let child, browser;
  let upstreamCalls = 0;
  const upstream = http.createServer(async (req, res) => {
    if (req.headers.authorization !== 'Bearer local-provider-test-key') { res.writeHead(401).end(); return; }
    res.setHeader('Content-Type', 'application/json');
    if (req.url === '/v1/models') { res.end(JSON.stringify({ data: [{ id: 'local-test-model' }] })); return; }
    upstreamCalls++;
    let body = ''; for await (const chunk of req) body += chunk;
    assert.equal(JSON.parse(body).model, 'local-test-model');
    res.end(JSON.stringify({ id: 'chat_test', object: 'chat.completion', created: 1, model: 'local-test-model', choices: [{ index: 0, message: { role: 'assistant', content: 'browser-test-answer' }, finish_reason: 'stop' }] }));
  });
  await new Promise(resolve => upstream.listen(0, '127.0.0.1', resolve));
  const upstreamURL = `http://127.0.0.1:${upstream.address().port}/v1`;
  async function start() {
    child = spawn(path.resolve(process.env.GOVWEAVE_TEST_BINARY || 'bin/govweave'), [], { env, stdio: ['ignore', 'ignore', 'pipe'] });
    let errors = '';
    child.stderr.on('data', chunk => { errors += chunk.toString(); });
    child.on('error', error => { errors += error.message; });
    for (let attempt = 0; attempt < 100; attempt++) {
      if (child.exitCode !== null) throw new Error(`Server exited: ${errors}`);
      try { if ((await fetch(`${origin}/healthz`)).ok) return; } catch {}
      await new Promise(resolve => setTimeout(resolve, 50));
    }
    throw new Error(`Server did not start: ${errors}`);
  }
  async function stop() {
    if (!child || child.exitCode !== null) return;
    const stopped = new Promise(resolve => child.once('exit', resolve));
    child.kill('SIGTERM');
    const timeout = setTimeout(() => child.kill('SIGKILL'), 6000);
    await stopped;
    clearTimeout(timeout);
  }
  try {
    await start();
    const password = 'browser test administrator password';
    browser = await chromium.launch({ executablePath: process.env.GOVWEAVE_BROWSER_PATH || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
    const errors = [], external = [];
    context.on('page', page => page.on('pageerror', error => errors.push(error.message)));
    context.on('request', request => { if (!request.url().startsWith(origin + '/')) external.push(request.url()); });
    const page = await context.newPage();
    await page.goto(origin);
    await page.waitForFunction(() => document.getElementById('service-status').textContent === '本地服务在线');
    await page.locator('#login-title').filter({ hasText: '设置管理员密码' }).waitFor();
    await page.screenshot({ path: path.join(output, 'password-setup.png'), fullPage: true, animations: 'disabled' });
    await page.locator('#admin-password').fill(password);
    await page.locator('#confirm-password').fill('different long password');
    await page.locator('#login-submit').click();
    await page.getByText('两次输入的密码不一致。', { exact: true }).waitFor();
    await page.locator('#confirm-password').fill(password);
    await page.locator('#login-submit').click();
    await page.locator('#dashboard').waitFor({ state: 'visible' });
    const savedPassword = await fs.readFile(path.join(dataDir, 'admin.password.json'), 'utf8');
    assert.ok(!savedPassword.includes(password));
    assert.equal(JSON.parse(savedPassword).algorithm, 'pbkdf2-sha256');
    await assert.rejects(fs.access(path.join(dataDir, 'admin.token')));
    await page.reload();
    await page.locator('#dashboard').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#admin-password').inputValue(), '');
    await page.locator('#logout').click();
    await page.locator('#login-panel').waitFor({ state: 'visible' });
    await page.screenshot({ path: path.join(output, 'login.png'), fullPage: true, animations: 'disabled' });
    await page.locator('#admin-password').fill('incorrect administrator password');
    await page.locator('#login-submit').click();
    await page.getByText('密码错误，请重试', { exact: true }).waitFor();
    async function login(target) {
      await target.locator('#admin-password').fill(password);
      await target.locator('#login-submit').click();
      await target.locator('#dashboard').waitFor({ state: 'visible' });
      await target.waitForFunction(() => document.getElementById('metric-models').textContent !== '—');
      assert.equal(await target.locator('#page-title').textContent(), '运行总览');
      await target.locator('.tabs [data-tab="deployment"]').click();
    }
    await login(page);
    await page.locator('.tabs [data-tab="overview"]').click();
    await page.locator('#overview-setup').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#metric-models').textContent(), '00');
    await page.screenshot({ path: path.join(output, 'overview-empty.png'), fullPage: true, animations: 'disabled' });
    await page.locator('.tabs [data-tab="deployment"]').click();
    await page.locator('#organization').fill('GovWeave 演示企业');
    await page.locator('#public-url').fill(`${origin}/v1`);
    await page.locator('#save-settings').click();
    await page.getByText('访问地址须为完整的 HTTP(S) 地址，不能包含账号、路径（包括 /v1）、查询参数或片段', { exact: true }).waitFor();
    await page.locator('#use-current').click();
    await page.locator('#save-settings').click();
    await page.getByText('实例地址已配置', { exact: true }).waitFor();
    assert.equal(await page.locator('#models-url').textContent(), `${origin}/v1`);
    assert.equal(await page.locator('#mcp-url').textContent(), `${origin}/mcp`);
    assert.match(await page.locator('#sdk-example').textContent(), /不能使用管理员密码/);
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
    const cookies = await context.cookies();
    assert.equal(cookies.length, 1);
    assert.equal(cookies[0].name, 'govweave_session');
    assert.equal(cookies[0].httpOnly, true);
    assert.equal(cookies[0].sameSite, 'Strict');
    assert.equal(await page.evaluate(() => document.cookie), '');
    const second = await context.newPage();
    await second.goto(origin);
    await second.locator('#dashboard').waitFor({ state: 'visible' });
    await second.locator('.tabs [data-tab="deployment"]').click();
    await page.locator('#organization').fill('GovWeave 企业平台');
    await page.locator('#save-settings').click();
    await page.locator('#save-meta').filter({ hasText: '保存版本 2' }).waitFor();
    await second.locator('#organization').fill('过期页面的修改');
    await second.locator('#save-settings').click();
    await second.getByText('配置已更新，请重新加载后再保存', { exact: true }).waitFor();
    await second.close();
    const pendingDownload = page.waitForEvent('download');
    await page.locator('#export-config').click();
    const download = await pendingDownload;
    const exported = JSON.parse(await fs.readFile(await download.path(), 'utf8'));
    assert.equal(exported.public_url, origin);
    assert.equal(exported.organization_name, 'GovWeave 企业平台');
    assert.ok(!JSON.stringify(exported).includes(password));
    await page.locator('.tabs [data-tab="connections"]').click();
    await page.locator('#new-connection').click();
    await page.locator('#connection-name').fill('本地测试模型');
    await page.locator('#connection-url').fill(upstreamURL);
    await page.locator('#connection-model').fill('local-test-model');
    await page.locator('#connection-alias').fill('internal-assistant');
    await page.screenshot({ path: path.join(output, 'connection-editor.png'), fullPage: true, animations: 'disabled' });
    await page.locator('#connection-key').fill('local-provider-test-key');
    await page.locator('#save-connection').click();
    await page.locator('#connection-editor .editor-notice').filter({ hasText: 'HTTP 上游未加密' }).waitFor();
    await page.locator('#connection-http').check();
    await page.locator('#save-connection').click();
    await page.locator('#connection-list').getByText('本地测试模型', { exact: true }).waitFor();
    assert.equal(await page.locator('#connection-key').inputValue(), '');
    assert.equal(await page.locator('#connection-editor').evaluate(dialog => dialog.open), false);
    await page.locator('#connection-search').fill('no-such-connection');
    await page.locator('#connection-list').getByText('没有找到匹配的连接', { exact: true }).waitFor();
    await page.locator('#connection-search').fill('');
    await page.locator('#connection-list').getByText('编辑', { exact: true }).click();
    assert.equal(await page.locator('#connection-key').inputValue(), '');
    assert.equal(await page.locator('#connection-alias').inputValue(), 'internal-assistant');
    await page.locator('#connection-editor').press('Escape');
    await page.locator('#connection-editor').waitFor({ state: 'hidden' });
    await page.locator('#connection-list').getByText('检查连接', { exact: true }).click();
    await page.locator('#notice').filter({ hasText: '连接成功' }).waitFor();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(output, 'connections.png'), fullPage: true, animations: 'disabled' });
    await page.locator('.tabs [data-tab="applications"]').click();
    await page.locator('#new-application').click();
    await page.locator('#application-name').fill('知识库测试应用');
    await page.locator('#application-grants input').check();
    await page.screenshot({ path: path.join(output, 'application-editor.png'), fullPage: true, animations: 'disabled' });
    await page.locator('#save-application').click();
    await page.locator('#new-key-panel').waitFor({ state: 'visible' });
    const appKey = await page.locator('#new-api-key').textContent();
    assert.ok(appKey.startsWith('gw_app_'));
    const invokeModel = async key => fetch(`${origin}/v1/chat/completions`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${key}` }, body: JSON.stringify({ model: 'internal-assistant', messages: [{ role: 'user', content: 'browser-test-prompt' }] }) });
    assert.equal((await invokeModel(appKey)).status, 200);
    await page.locator('#dismiss-key').click();
    assert.equal(await page.locator('#new-api-key').textContent(), '');
    await page.screenshot({ path: path.join(output, 'applications.png'), fullPage: true, animations: 'disabled' });
    await page.locator('.tabs [data-tab="requests"]').click();
    await page.locator('#request-list').getByText('已完成 · 200', { exact: true }).first().waitFor();
    assert.ok(!(await page.locator('#request-list').textContent()).includes('browser-test-prompt'));
    await page.screenshot({ path: path.join(output, 'requests.png'), fullPage: true, animations: 'disabled' });
    await page.locator('#request-list .request-open').first().click();
    await page.locator('#request-detail').waitFor({ state: 'visible' });
    assert.ok(!(await page.locator('#request-detail').textContent()).includes('browser-test-prompt'));
    assert.ok(!(await page.locator('#request-detail').textContent()).includes('browser-test-answer'));
    assert.match(await page.locator('#detail-request-id').textContent(), /^req_/);
    await page.screenshot({ path: path.join(output, 'request-detail.png'), fullPage: true, animations: 'disabled' });
    await page.locator('#request-detail').press('Escape');
    await page.locator('.tabs [data-tab="applications"]').click();
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#application-list').getByText('轮换密钥', { exact: true }).click();
    await page.locator('#new-key-panel').waitFor({ state: 'visible' });
    const rotated = await page.locator('#new-api-key').textContent();
    assert.notEqual(appKey, rotated);
    assert.equal((await invokeModel(appKey)).status, 401);
    assert.equal((await invokeModel(rotated)).status, 200);
    await page.locator('#dismiss-key').click();
    await page.locator('.tabs [data-tab="deployment"]').click();
    await page.locator('#sdk-example').filter({ hasText: 'internal-assistant' }).waitFor();
    assert.ok((await page.locator('#sdk-example').textContent()).includes(origin));
    assert.ok(!(await page.locator('#sdk-example').textContent()).includes(rotated));
    await page.locator('.tabs [data-tab="overview"]').click();
    await page.locator('#metric-requests').filter({ hasText: '03' }).waitFor();
    assert.equal(await page.locator('#metric-issues').textContent(), '01');
    assert.equal(await page.locator('#metric-models').textContent(), '01');
    assert.equal(await page.locator('#metric-apps').textContent(), '01');
    await page.screenshot({ path: path.join(output, 'overview.png'), fullPage: true, animations: 'disabled' });
    await page.locator('.tabs [data-tab="deployment"]').click();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true, animations: 'disabled' });
    for (const tab of ['overview', 'connections', 'applications', 'requests']) {
      await page.locator(`.tabs [data-tab="${tab}"]`).click();
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
      await page.screenshot({ path: path.join(output, `mobile-${tab}.png`), fullPage: true, animations: 'disabled' });
    }
    await page.locator('.tabs [data-tab="connections"]').click();
    await page.locator('#new-connection').click();
    await page.locator('#connection-editor').waitFor({ state: 'visible' });
    assert.ok(await page.locator('#connection-editor').evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth));
    await page.screenshot({ path: path.join(output, 'mobile-editor.png'), fullPage: true, animations: 'disabled' });
    await page.locator('#connection-editor').press('Escape');
    await stop();
    await start();
    await page.reload();
    await page.locator('#login-panel').waitFor({ state: 'visible' });
    await login(page);
    assert.equal(await page.locator('#organization').inputValue(), 'GovWeave 企业平台');
    assert.equal(await page.locator('#public-url').inputValue(), origin);
    assert.equal((await invokeModel(rotated)).status, 200);
    await page.locator('.tabs [data-tab="applications"]').click();
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#application-list').getByText('撤销应用', { exact: true }).click();
    await page.locator('#application-list').getByText('已撤销', { exact: true }).waitFor();
    assert.equal((await invokeModel(rotated)).status, 401);
    assert.equal(upstreamCalls, 3);
    await page.locator('#logout').click();
    await page.locator('#login-panel').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#admin-password').inputValue(), '');
    assert.equal((await context.cookies()).length, 0);
    await page.reload();
    await page.locator('#login-title').filter({ hasText: '欢迎回来' }).waitFor();
    assert.equal(await page.locator('#confirm-password-field').isVisible(), false);
    await page.screenshot({ path: path.join(output, 'mobile-login.png'), fullPage: true, animations: 'disabled' });
    assert.deepEqual(errors, []);
    assert.deepEqual(external, []);
    console.log('Browser smoke passed: initial password setup, confirmation, password login, HttpOnly sessions, refresh persistence, logout revocation, validation, initialization, concurrent edits, export, desktop/mobile, restart, no storage credentials, no external browser requests, connection check, application grants, SDK example, inference, call records, key rotation and revocation, overview metrics, search, editor keyboard dismissal, request inspector.');
    console.log(`Screenshots: ${output}`);
  } finally {
    if (browser) await browser.close();
    await stop();
    await new Promise(resolve => upstream.close(resolve));
    await fs.rm(dataDir, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
