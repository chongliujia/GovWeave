const preferenceKey = "govweave.locale";
let locale = "en";
const listeners = new Set();

export function t(key, values = {}) {
  if (key === undefined || key === null) return "";
  const source = locale === "zh-CN" && Object.hasOwn(chinese, key) ? chinese[key] : key;
  return source.replace(/\{([a-zA-Z]+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
export function getLocale() { return locale; }
export function formatDateTime(value) { return new Date(value).toLocaleString(locale === "en" ? "en-GB" : "zh-CN", { hour12: false }); }
export function formatTime(value) { return new Date(value).toLocaleTimeString(locale === "en" ? "en-GB" : "zh-CN", { hour12: false }); }
export function onLocaleChange(listener) { listeners.add(listener); return () => listeners.delete(listener); }

function applyStaticText() {
  document.documentElement.lang = locale;
  document.querySelectorAll("[data-i18n-parts]").forEach(element => {
    const parts = JSON.parse(element.dataset.i18nParts);
    for (const [index, message] of Object.entries(parts)) {
      const text = element.childNodes[Number(index)];
      if (text?.nodeType !== Node.TEXT_NODE) continue;
      const trimmed = message.trim();
      text.nodeValue = message.replace(trimmed, t(trimmed));
    }
  });
  for (const attribute of ["placeholder", "title", "aria-label"]) {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
      element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
    });
  }
  document.querySelectorAll("[data-language-select]").forEach(select => { select.value = locale; });
  document.querySelectorAll("input").forEach(input => input.setCustomValidity(""));
}

export function setLocale(value, persist = true) {
  const next = value === "zh-CN" ? "zh-CN" : "en";
  locale = next;
  if (persist) { try { localStorage.setItem(preferenceKey, locale); } catch { /* Keep this page usable when storage is disabled. */ } }
  applyStaticText();
  for (const listener of listeners) listener();
}

export function initializeLocale() {
  let saved = "en";
  try { saved = localStorage.getItem(preferenceKey) || "en"; } catch { /* Default to English. */ }
  setLocale(saved, false);
  document.querySelectorAll("[data-language-select]").forEach(select => select.addEventListener("change", () => setLocale(select.value)));
  window.addEventListener("storage", event => { if (event.key === preferenceKey) setLocale(event.newValue, false); });
  document.addEventListener("input", event => { if (event.target instanceof HTMLInputElement) event.target.setCustomValidity(""); });
  document.addEventListener("invalid", event => {
    const input = event.target;
    if (!(input instanceof HTMLInputElement)) return;
    input.setCustomValidity("");
    const v = input.validity;
    if (v.valueMissing) input.setCustomValidity(t("Please fill out this field."));
    else if (v.typeMismatch && input.type === "url") input.setCustomValidity(t("Enter a valid URL."));
    else if (v.tooShort) input.setCustomValidity(t("Enter at least {min} characters.", { min: input.minLength }));
    else if (v.tooLong) input.setCustomValidity(t("Use no more than {max} characters.", { max: input.maxLength }));
    else if (v.rangeUnderflow || v.rangeOverflow) input.setCustomValidity(t("Enter a number between {min} and {max}.", { min: input.min, max: input.max }));
    else if (!v.valid) input.setCustomValidity(t("Enter a valid value."));
  }, true);
}
